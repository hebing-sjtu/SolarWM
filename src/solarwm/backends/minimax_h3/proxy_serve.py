"""A resident H3 proxy generator that serves takes from a spool directory.

The model loads once; a front end (FastVideo's ``proxy_service.py``) encodes each request into
cached 124-frame segments and drops a job file into the spool. Any number of workers, each one
SP group (typically SP1, one per GPU), share a spool; claiming a job is an atomic rename, so
each job goes to exactly one of them. Inside a worker, rank 0 polls and broadcasts what it found
every ``POLL_SECONDS``, so a wide group runs one tiny collective while idle instead of sitting in
a collective that would time out. A job is a take of one or more segments and is generated by
:func:`proxy_rollout.roll_segments`, exactly as a long rollout.

Spool layout::

    queue/<id>.json          submitted jobs (written elsewhere, renamed in atomically)
    running/<id>.json        the job being generated, with <id>.progress.json beside it
    out/<id>/                take.mp4, take_compare.mp4, segments/
    done/<id>.json           the result, or {"error": ...}; written last
    workers/<name>.json      per-worker heartbeat: state, current job, weights
    STOP                     makes every worker exit after its current job
"""

from __future__ import annotations

import copy
import json
import os
import time
import traceback
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from solarwm.errors import BackendContractError, DataContractError

from .proxy_artifacts import CWM_CONTINUATION_ROLES
from .proxy_rollout import STRIDE_FRAMES, TakeSegment, _WriterState, roll_segments, take_frames

JOB_SCHEMA = "h3-proxy-serve-job.v1"
POLL_SECONDS = 2.0
MAX_SEGMENTS = 16


def _write_json(path: Path, payload: Mapping[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    scratch = path.with_name(f".{path.name}.tmp")
    scratch.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    os.replace(scratch, path)


def job_segments(job: Mapping[str, Any], *, base_role: str) -> tuple[TakeSegment, ...]:
    """The job's segments, checked against the take geometry and the run's CWM roles."""

    if job.get("schema") != JOB_SCHEMA:
        raise DataContractError(f"serve job is not {JOB_SCHEMA}")
    rows = job.get("segments")
    if not isinstance(rows, list) or not rows:
        raise DataContractError("serve job lists no segments")
    if len(rows) > MAX_SEGMENTS:
        raise DataContractError(f"serve job has {len(rows)} segments, at most {MAX_SEGMENTS}")
    role = str(base_role).strip().lower()
    continuation = CWM_CONTINUATION_ROLES.get(role)
    if continuation is None and len(rows) > 1:
        raise DataContractError(f"CWM role {role!r} has no continuation role for a long take")
    segments = []
    for index, row in enumerate(rows):
        expected = role if index == 0 else continuation
        if str(row.get("cwm_system") or "").strip().lower() != expected:
            raise DataContractError(f"segment {index} must use CWM role {expected!r}")
        path = Path(str(row.get("pt") or ""))
        if not path.is_absolute() or not path.is_file():
            raise DataContractError(f"segment {index} sample is missing: {path}")
        segments.append(
            TakeSegment(index, str(row.get("name") or path.stem), path, index * STRIDE_FRAMES, expected)
        )
    frames = int(job.get("frames") or take_frames(len(segments)))
    if not 1 <= frames <= take_frames(len(segments)):
        raise DataContractError(f"serve job frames={frames} exceed what {len(segments)} segments make")
    return tuple(segments)


class Spool:
    """SP rank 0's view of the spool directory."""

    def __init__(self, root: Path, worker: str = "worker") -> None:
        self.root = root
        self.worker = worker
        for name in ("queue", "running", "out", "done", "workers"):
            (root / name).mkdir(parents=True, exist_ok=True)

    def heartbeat(self, state: str, runtime: Any, job: str | None = None) -> None:
        _write_json(
            self.root / "workers" / f"{self.worker}.json",
            {
                "worker": self.worker,
                "state": state,
                "job": job,
                "pid": os.getpid(),
                "updated": time.time(),
                "weights_id": runtime.weights_id,
                "checkpoint": runtime.checkpoint_path or None,
                "weight_source": runtime.weight_source,
                "generation": runtime.generation,
            },
        )

    def claim(self) -> dict[str, Any] | None:
        """The oldest queued job, moved to ``running/``; a malformed one is failed on the spot."""

        queued = []
        for path in self.root.glob("queue/*.json"):
            try:
                queued.append((path.stat().st_mtime, path.name, path))
            except FileNotFoundError:
                continue  # claimed by another worker since the listing
        for _, _, path in sorted(queued):
            running = self.root / "running" / path.name
            try:
                os.replace(path, running)
            except FileNotFoundError:
                continue  # another worker claimed it first
            try:
                job = json.loads(running.read_text(encoding="utf-8"))
            except (OSError, ValueError) as exc:
                self.finish(path.stem, {"error": f"unreadable job: {exc}"})
                continue
            job["id"] = path.stem
            job["worker"] = self.worker
            return job
        return None

    def progress(self, job_id: str, done: int, total: int) -> None:
        _write_json(
            self.root / "running" / f"{job_id}.progress.json",
            {"done": done, "total": total, "updated": time.time()},
        )

    def finish(self, job_id: str, payload: Mapping[str, Any]) -> None:
        _write_json(self.root / "done" / f"{job_id}.json", {"id": job_id, **payload})
        for name in (f"{job_id}.json", f"{job_id}.progress.json"):
            (self.root / "running" / name).unlink(missing_ok=True)

    def stopping(self) -> bool:
        return (self.root / "STOP").exists()


def run_proxy_serve(config: Mapping[str, Any]) -> int:
    """Load the model once, then generate spooled jobs until ``STOP`` appears."""

    from .distributed import get_sp_rank
    from .proxy_artifacts import H3ProxyPtStream
    from .proxy_inference import load_proxy_runtime

    inference = config["inference"]
    data = config["data"]
    runtime = load_proxy_runtime(config)
    torch, dist, topology = runtime.torch, runtime.dist, runtime.topology
    if int(topology.dp_world_size) != 1:
        raise BackendContractError(
            "inference.proxy_serve runs one SP group; set sequence_parallel_size to the world size"
        )
    runtime.core.continuation = True
    reader = H3ProxyPtStream(copy.deepcopy(dict(config)), topology, continuation=True)
    leader = int(topology.raw_rank) == 0
    worker = os.environ.get("H3_SERVE_WORKER") or f"pid{os.getpid()}"
    spool = Spool(Path(str(inference["proxy_serve"])).resolve(), worker) if leader else None
    default_steps = int(config["validation"]["num_inference_steps"])
    default_seed = int(config["validation"]["noise_seed"])
    writer = _WriterState()
    base_role = str(data["cwm_system"])
    if spool is not None:
        spool.heartbeat("idle", runtime)
        print(
            f"[h3-proxy-serve] {worker} ready: {runtime.weights_id} SP{topology.sp_size} "
            f"spool={spool.root}",
            flush=True,
        )

    try:
        while True:
            message: list[Any] = [None]
            if spool is not None:
                if spool.stopping():
                    message = [{"stop": True}]
                else:
                    job = spool.claim()
                    if job is not None:
                        try:
                            segments = job_segments(job, base_role=base_role)
                            message = [{"job": job, "segments": [str(s.path) for s in segments]}]
                        except DataContractError as exc:
                            spool.finish(job["id"], {"error": str(exc)})
            if dist.is_initialized():
                dist.broadcast_object_list(message, src=0)
            command = message[0]
            if command is None:
                if spool is not None:
                    spool.heartbeat("idle", runtime)
                time.sleep(POLL_SECONDS)
                continue
            if command.get("stop"):
                break
            job = command["job"]
            job_id = str(job["id"])
            segments = job_segments(job, base_role=base_role)
            out = (
                Path(str(inference["proxy_serve"])).resolve() / "out" / job_id
                if get_sp_rank() == 0
                else Path("/nonexistent")
            )
            if spool is not None:
                spool.heartbeat("busy", runtime, job_id)
                spool.progress(job_id, 0, len(segments))
            started = time.time()
            steps = int(job.get("steps") or default_steps)
            seed = int(job.get("seed") if job.get("seed") is not None else default_seed)
            frames = int(job.get("frames") or take_frames(len(segments)))
            try:
                records = roll_segments(
                    runtime,
                    reader,
                    segments,
                    config=config,
                    root=out,
                    fps=int(job.get("fps") or 24),
                    real_target=False,
                    seed=seed,
                    steps=steps,
                    writer=writer,
                    max_frames=frames,
                    progress=(lambda done, total: spool.progress(job_id, done, total))
                    if spool is not None
                    else None,
                )
                error = ""
            except Exception as exc:
                records, error = [], f"{type(exc).__name__}: {exc}"
                if leader:
                    traceback.print_exc()
            if spool is not None:
                result: dict[str, Any] = {
                    "worker": worker,
                    "seconds": round(time.time() - started, 1),
                    "weights_id": runtime.weights_id,
                    "num_inference_steps": steps,
                    "noise_seed": seed,
                    "frames": frames,
                    **runtime.generation,
                }
                if error:
                    result["error"] = error
                else:
                    result.update(
                        {
                            "take": str(out / "take.mp4"),
                            "compare": str(out / "take_compare.mp4"),
                            "panel_order": ["proxy", "prediction"],
                            "segments": records,
                        }
                    )
                spool.finish(job_id, result)
                print(
                    f"[h3-proxy-serve] {worker} job {job_id}: {len(segments)} segment(s) "
                    f"{'failed: ' + error if error else 'done'} in {result['seconds']}s",
                    flush=True,
                )
            # A causal core caches window masks per prompt; the next job's prompt never matches.
            release = getattr(runtime.core, "release_window_cache", None)
            if release is not None:
                release()
            torch.cuda.empty_cache()
    finally:
        reader.close()
        if spool is not None:
            spool.heartbeat("stopped", runtime)
    return 0


__all__ = ["JOB_SCHEMA", "Spool", "job_segments", "run_proxy_serve"]
